const EN = {};
document.querySelectorAll("[data-i]").forEach(el => { EN[el.dataset.i] = el.innerHTML; });
// SVG <text> has no innerHTML in every browser, so use textContent there.
function setLang(tr) {
  const dict = tr ? TR : EN;
  document.documentElement.lang = tr ? "tr" : "en";
  document.querySelectorAll("[data-i]").forEach(el => {
    const v = dict[el.dataset.i];
    if (v == null) return;
    if (el instanceof SVGElement) el.textContent = v; else el.innerHTML = v;
  });
  document.getElementById("lang").textContent = tr ? "EN" : "TR";
  try { localStorage.setItem("mysy-lang", tr ? "tr" : "en"); } catch (e) {}
}
let saved = null;
try { saved = localStorage.getItem("mysy-lang"); } catch (e) {}
// Every page has an English URL and a Turkish one under /tr/, linked by hreflang. The button goes to the other one.
const isTr = document.documentElement.lang === "tr";
const twin = document.querySelector(`link[rel="alternate"][hreflang="${isTr ? "en" : "tr"}"]`);
if (twin) {
  const local = new URL(twin.href).pathname;
  const want = saved ? saved === "tr" : isTr || (navigator.language || "").toLowerCase().startsWith("tr");
  if (want !== isTr && location.protocol !== "file:") location.replace(local + location.hash);
  document.getElementById("lang").addEventListener("click", () => {
    try { localStorage.setItem("mysy-lang", isTr ? "en" : "tr"); } catch (e) {}
    location.href = local + location.hash;
  });
} else {
  let tr = saved ? saved === "tr" : (navigator.language || "").toLowerCase().startsWith("tr");
  if (tr !== isTr) setLang(tr);
  document.getElementById("lang").addEventListener("click", () => { tr = !tr; setLang(tr); });
}

